#!/bin/bash
#
# gen-skills-manifest.sh — Record linked skills in SKILLS.md instead of committing them
#
# Entries in skills/ are a mix of real directories (authored here, tracked) and
# symlinks out to ~/.agents/skills and other local repos. Committing a symlink
# stores only its target, an absolute path under this machine's home directory,
# so anyone who clones the repo gets a dangling link and no content.
#
# So symlinks are not tracked at all. This script writes two files:
#
#   SKILLS.md          human-readable list of linked skills and where each came from
#   skills/.gitignore  the symlink names, so git stops seeing them
#
# Provenance comes from ~/.agents/.skill-lock.json, the lockfile skills.sh
# writes when it installs a skill. Links that predate the lockfile, or that
# point at a local repo, cannot be reinstalled from a source URL; those are
# listed under their own heading rather than dropped, so the gap stays visible.
#
# Usage:
#   gen-skills-manifest.sh          regenerate both files
#   gen-skills-manifest.sh --check  exit 1 if either file is out of date

set -euo pipefail

REPO_DIR="$(cd "$(dirname "$0")/.." && pwd -P)"
SKILLS_DIR="$REPO_DIR/skills"
LOCK="$HOME/.agents/.skill-lock.json"
MANIFEST="$REPO_DIR/SKILLS.md"
IGNORE="$SKILLS_DIR/.gitignore"

CHECK_ONLY=0
[ "${1:-}" = "--check" ] && CHECK_ONLY=1

command -v jq >/dev/null || { echo "gen-skills-manifest: jq is required" >&2; exit 1; }
[ -d "$SKILLS_DIR" ] || { echo "gen-skills-manifest: no skills/ directory" >&2; exit 1; }

# Without the lockfile we can still list what is linked, just not where it came from.
if [ ! -f "$LOCK" ]; then
    echo "gen-skills-manifest: warning: $LOCK not found; sources will be unknown" >&2
    LOCK=""
fi

lookup() { # name field -> value, empty if absent
    [ -n "$LOCK" ] || return 0
    jq -r --arg n "$1" --arg f "$2" '.skills[$n][$f] // empty' "$LOCK"
}

TILDE='~'    # kept in a variable so it never undergoes tilde expansion

tracked=""   # rows for skills installed by skills.sh
untracked="" # rows for links with no lockfile entry
local_dirs=""
names=""

broken=""

for entry in "$SKILLS_DIR"/*; do
    name=$(basename "$entry")

    # A dangling link must be reported, not skipped. skills.sh writes its links
    # relative ("../../.agents/skills/x"), which assumes skills/ really lives at
    # ~/.claude/skills; here that path is itself a symlink into this repo, so a
    # relative link resolves against the repo and misses. Silently dropping
    # those makes a skill vanish from the manifest with no explanation.
    if [ -L "$entry" ] && [ ! -e "$entry" ]; then
        broken="$broken  $name -> $(readlink "$entry")"$'\n'
        continue
    fi
    [ -e "$entry" ] || continue

    if [ ! -L "$entry" ]; then
        [ -f "$entry/SKILL.md" ] && local_dirs="$local_dirs- \`$name\`"$'\n'
        continue
    fi

    names="$names$name"$'\n'
    target=$(readlink "$entry")
    source=$(lookup "$name" source)

    if [ -n "$source" ]; then
        url=$(lookup "$name" sourceUrl)
        updated=$(lookup "$name" updatedAt | cut -c1-10)
        repo=${url%.git}
        tracked="$tracked| \`$name\` | [$source]($repo) | $updated |"$'\n'
    else
        # Show the path relative to home so the manifest is not machine-specific noise.
        short=$TILDE${target#"$HOME"}
        [ "$target" = "${target#"$HOME"}" ] && short=$target
        untracked="$untracked| \`$name\` | \`$short\` |"$'\n'
    fi
done

link_count=$(printf '%s' "$names" | grep -c . || true)

if [ -n "$broken" ]; then
    echo "gen-skills-manifest: warning: dangling symlinks in skills/, omitted from the manifest:" >&2
    printf '%s' "$broken" >&2
    echo "  fix with: ln -sfn \"\$HOME/.agents/skills/<name>\" skills/<name>" >&2
fi

manifest_body="<!-- Generated by scripts/gen-skills-manifest.sh. Do not edit by hand. -->

# Linked skills

Not every skill in this repo is stored here. \`skills/\` holds a mix of
directories authored in this repo and symlinks out to skills installed
elsewhere, mostly by [skills.sh](https://skills.sh) into \`~/.agents/skills\`.

The symlinks are deliberately **not committed**. A symlink stores only its
target, and those targets are absolute paths under one machine's home
directory, so committing them would give anyone else a dangling link pointing
at a directory they do not have. This file records what is linked and where it
came from instead, so the set can be rebuilt on another machine.

Regenerate with \`./scripts/gen-skills-manifest.sh\` after adding or removing a skill.

## Installed via skills.sh ($(printf '%s' "$tracked" | grep -c . || true))

Reinstall any of these with \`npx skills add <source>\`.

| Skill | Source | Updated |
|---|---|---|
$tracked"

if [ -n "$untracked" ]; then
    manifest_body="$manifest_body
## Linked, source not recorded ($(printf '%s' "$untracked" | grep -c . || true))

These have no entry in the skills.sh lockfile, so there is no source URL to
reinstall from. A link into \`~/.agents/skills\` here means the skill was put
there by hand rather than by \`npx skills add\`; a link anywhere else points at
another repo on this machine, which has to be cloned separately.

| Skill | Link target |
|---|---|
$untracked"
fi

manifest_body="$manifest_body
## Authored in this repo ($(printf '%s' "$local_dirs" | grep -c . || true))

Real directories, tracked in git, no external source.

$local_dirs"

ignore_body="# Generated by scripts/gen-skills-manifest.sh. Do not edit by hand.
#
# Symlinked skills. Their targets are absolute paths on one machine, so they
# are recorded in SKILLS.md rather than committed. See that file for sources.

$names"

if [ "$CHECK_ONLY" = "1" ]; then
    # Compare through printf/diff rather than $(cat …), which strips trailing
    # newlines and would report a freshly written file as stale.
    stale=0
    printf '%s' "$manifest_body" | diff -q - "$MANIFEST" >/dev/null 2>&1 || stale=1
    printf '%s' "$ignore_body"   | diff -q - "$IGNORE"   >/dev/null 2>&1 || stale=1
    if [ "$stale" = "1" ]; then
        echo "SKILLS.md or skills/.gitignore is out of date; run ./scripts/gen-skills-manifest.sh"
        exit 1
    fi
    echo "Skill manifest is up to date ($link_count linked)."
    exit 0
fi

printf '%s' "$manifest_body" > "$MANIFEST"
printf '%s' "$ignore_body" > "$IGNORE"

echo "Wrote SKILLS.md and skills/.gitignore ($link_count linked skills)."
